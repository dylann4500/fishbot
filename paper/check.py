#!/usr/bin/env python3
"""Consistency sweep for the FishBot manuscripts.

Run from anywhere:

    python3 paper/check.py            # every manuscript present (v0.4 and v0.5)
    python3 paper/check.py --v04      # the v0.4 manuscript only
    python3 paper/check.py --v05      # the v0.5 manuscript only

Three classes of check, all of which have caught real defects in these papers:

  1. BANNED  -- phrases the review of that version ruled out.  For v0.4, e.g.
     calling the declaration rule "optimal", calling the two-ply refinement
     "exact", or asserting an upper bound on exploitability.  For v0.5, e.g.
     calling the deadlock an information freeze, calling an allocation
     probability computed on the deployed approximate belief "exact", or
     asserting an upper bound on exploitability.
  2. MACROS  -- every \\num... macro referenced by a section must be defined in
     that manuscript's numbers file (generated by engine/build_tables.py, with a
     hand-written \\providecommand placeholder until the generator covers it),
     and macros that already carry a percent sign must not be followed by
     another.
  3. STRUCTURE -- every \\ref/\\eqref resolves, every \\cite resolves, every
     \\input names a file that exists, and no table or figure lacks a caption or
     a label.

Exit status is non-zero if anything in class 1 or 2 fires in any manuscript, or
if class 3 finds a dangling reference.
"""
