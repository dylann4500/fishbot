# Several banned phrases are legitimate inside an explicit disclaimer -- the
# paper is required to say, for instance, that the rule is "not a Bellman-optimal
# stopping value".  A hit is suppressed when a negation cue appears close by.
NEGATION_BASE = (
    r'\b(?:not|never|no longer|rather than|instead of|does not|do not|is not|are not|'
    r'without|nor|neither|cannot|avoid|deny|denies|refrain|but not|other than|'
    r'we make no|makes no|no such|misleading|incorrect|wrong|must not)\b'
)
# The v0.5 manuscript quotes the claims it retracts, so the corrections section
# needs a wider set of cues than a plain negation.
NEGATION_V05_EXTRA = (
    r'|\b(?:false|retract\w*|withdraw\w*|withdrawn|corrected|correction|corrects|'
    r'refut\w*|erroneous|overstate\w*|understate\w*|fails|failed|stale|priced|'
    r'unbuilt|not yet)\b'
)
NEG_WINDOW = 220


class Profile:
    def __init__(self, name, master, sections, numbers, banned, self_percent,
                 negation, extra_dirs):
        self.name = name
        self.master = os.path.join(HERE, master)
        self.sections = os.path.join(HERE, sections)
        self.numbers = os.path.join(HERE, numbers)
        self.banned = banned
        self.self_percent = self_percent
        self.negation = re.compile(negation, re.IGNORECASE)
        self.extra_dirs = [os.path.join(HERE, d) for d in extra_dirs]

    def present(self):
        return os.path.exists(self.master) and os.path.isdir(self.sections)



